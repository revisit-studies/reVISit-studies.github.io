import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

test('production and preview publishing replace stale files and preserve other previews', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'revisit-pages-test-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const pages = path.join(root, 'pages');
  const build = path.join(root, 'build');
  const remote = path.join(root, 'remote.git');
  await mkdir(path.join(pages, 'PR12'), { recursive: true });
  await mkdir(path.join(pages, 'PR13'), { recursive: true });
  await mkdir(build);
  const git = (...args) => execFileSync('git', args, { cwd: pages, encoding: 'utf8', stdio: 'pipe' }).trim();
  git('init', '--quiet', '--initial-branch=gh-pages');
  git('init', '--bare', '--quiet', remote);
  git('remote', 'add', 'origin', remote);
  await writeFile(path.join(pages, 'stale.html'), 'old route');
  await writeFile(path.join(pages, 'PR12/stale.html'), 'old preview route');
  await writeFile(path.join(pages, 'PR13/index.html'), 'other preview');
  git('add', '--all');
  git('-c', 'user.name=Test', '-c', 'user.email=test@example.com', 'commit', '--quiet', '-m', 'Initial site');
  git('push', '--quiet', 'origin', 'gh-pages');
  await writeFile(path.join(build, 'index.html'), 'new site');
  const publish = (...args) => execFileSync('bash', [path.resolve('scripts/publishPages.sh'), ...args], { stdio: 'pipe' });
  publish(build, pages);
  assert.equal(await readFile(path.join(pages, 'index.html'), 'utf8'), 'new site');
  assert.equal(await readFile(path.join(pages, 'PR13/index.html'), 'utf8'), 'other preview');
  assert.equal(await readFile(path.join(pages, 'PR12/stale.html'), 'utf8'), 'old preview route');
  await assert.rejects(readFile(path.join(pages, 'stale.html')), { code: 'ENOENT' });
  assert.equal(await readFile(path.join(pages, 'CNAME'), 'utf8'), 'revisit.dev\n');
  publish(build, pages, 'PR12');
  await assert.rejects(readFile(path.join(pages, 'PR12/stale.html')), { code: 'ENOENT' });
  assert.equal(await readFile(path.join(pages, 'PR12/index.html'), 'utf8'), 'new site');
  publish('--delete', pages, 'PR12');
  await assert.rejects(readFile(path.join(pages, 'PR12/index.html')), { code: 'ENOENT' });
  assert.equal(await readFile(path.join(pages, 'PR13/index.html'), 'utf8'), 'other preview');
  const head = git('rev-parse', 'HEAD');
  publish('--delete', pages, 'PR12');
  assert.equal(git('rev-parse', 'HEAD'), head);
  assert.throws(() => publish('--delete', pages, '../escape'));
});
